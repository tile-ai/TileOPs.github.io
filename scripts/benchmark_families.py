def _build_op_family() -> dict[str, str]:
    result: dict[str, str] = {}
    for family, ops in FAMILY_OPS.items():
        for op in ops:
            if op in result:
                raise ValueError(
                    f"benchmark op {op!r} is declared in both "
                    f"{result[op]!r} and {family!r}"
                )
            result[op] = family
    return result


OP_FAMILY = _build_op_family()
